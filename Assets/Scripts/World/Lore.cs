        public class BossInfo
        {
            public string Name, Title;
        }

        public static BossInfo Boss(string id)
        {
            switch (id)
            {
                case "gornan": return new BossInfo { Title = "Угольный Кузнец", Name = "ГОРНАН" };
                case "weaver": return new BossInfo { Title = "Ткачиха Сажи", Name = "МОРРА" };
                case "king": return new BossInfo { Title = "Король-Огарок", Name = "ТАЛЛОУ" };
            }
            return new BossInfo { Title = "", Name = id };
        }

