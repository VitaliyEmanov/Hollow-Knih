    /// <summary>A link from a door (digit in the map) to another room's door.</summary>
    public struct DoorLink
    {
        public string Room;
        public char Door;
        public DoorLink(string room, char door) { Room = room; Door = door; }
    }

    /// <summary>
    /// Static description of a room. Maps are ASCII, first string = top row.
    ///  #  rock            =  one-way ledge      ^  ash thorns       ~  molten wax
    ///  P  new game start  B  candelabra (rest)  N  NPC              T  lore tablet
    ///  A  ability altar   S  wax shard          K  boss             G  boss gate
    ///  c  ash crawler     m  soot moth          h  cinder husk      s  ash spitter
    ///  w  ember wisp      1..9  doors
    /// </summary>
    public sealed class RoomDef
    {
        public string Id;
        public int Area;
        public string[] Map;
        public Dictionary<char, DoorLink> Doors = new Dictionary<char, DoorLink>();
        public string[] Tablets = new string[0];
        public string NpcId;
        public string Boss;
        public float BossTriggerX = -1f;
        public string Ability; // granted by altar 'A'

        public int W { get { return Map[0].Length; } }
        public int H { get { return Map.Length; } }

        /// <summary>Tile at (x, y) with y pointing UP (0 = bottom row).</summary>
        public char At(int x, int y)
        {
            if (x < 0 || y < 0 || x >= W || y >= H) return '#';
            return Map[H - 1 - y][x];
        }
    }

