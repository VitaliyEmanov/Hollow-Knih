        public static RoomDef Get(string id)
        {
            if (all == null) Build();
            RoomDef r;
            return all.TryGetValue(id, out r) ? r : null;
        }

        public static IEnumerable<RoomDef> All
        {
            get { if (all == null) Build(); return all.Values; }
        }

